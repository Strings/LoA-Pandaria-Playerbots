"""Regenerate the twink candidate table for the GM test suite's twink_gear checkpoint step (T-048).

Runs T-045's shortlist query (docs/twinks.md, "Reproduce the database shortlist") with one change: the top two
are kept per primary stat too (strength, agility, intellect or spell power), so every spec has candidates. Each
item is stored once, at the lowest bracket it qualifies for, and the result is written as an idempotent world
update. Read-only against the database.

    python tools/gmtools/twink_candidates.py --database world_claude --output sql/updates/world/<file>.sql

Credentials come from MOP_DB_USER / MOP_DB_PASSWORD (default ultimatemop), the client from MOP_MYSQL
(default the MySQL 8.0 install path).
"""

import argparse
import os
import re
import subprocess

STAT_TYPES = {'strength': [4], 'agility': [3], 'intellect': [5, 45]}
BITS = {'strength': 1, 'agility': 2, 'intellect': 4}


def shortlist_query(doc_path):
    text = open(doc_path, encoding='utf-8').read()
    section = text.split('## Reproduce the database shortlist', 1)[1]
    query = re.search(r'```sql\n(.*?)```', section, re.S).group(1)

    def has(types):
        return ' OR '.join('i.stat_type%d=%d' % (n, t) for t in types for n in range(1, 11))

    group = ' + '.join('(CASE WHEN (%s) THEN %d ELSE 0 END)' % (has(STAT_TYPES[s]), BITS[s]) for s in BITS)
    old = 'ROW_NUMBER() OVER (PARTITION BY l.lvl,i.Class,i.SubClass,i.InventoryType ORDER BY'
    assert old in query, 'the T-045 query changed; update this script'
    query = query.replace(old, 'ROW_NUMBER() OVER (PARTITION BY l.lvl,i.Class,i.SubClass,i.InventoryType,%s ORDER BY' % group)
    query = re.sub(r'SELECT bracket,entry,name,.*?;\s*$', 'SELECT bracket,entry FROM ranked WHERE rnk<=2;', query, flags=re.S)
    return query


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--database', required=True)
    parser.add_argument('--output', required=True)
    parser.add_argument('--doc', default=os.path.join(os.path.dirname(__file__), '..', '..', 'docs', 'twinks.md'))
    args = parser.parse_args()

    mysql = os.environ.get('MOP_MYSQL', r'C:\Program Files\MySQL\MySQL Server 8.0\bin\mysql.exe')
    user = os.environ.get('MOP_DB_USER', 'ultimatemop')
    env = dict(os.environ, MYSQL_PWD=os.environ.get('MOP_DB_PASSWORD', 'ultimatemop'))
    out = subprocess.run([mysql, '-u' + user, '-N', args.database], input=shortlist_query(args.doc), env=env,
                         capture_output=True, text=True, check=True).stdout

    lowest = {}
    for line in out.splitlines():
        bracket, entry = (int(v) for v in line.split('\t'))
        lowest[entry] = min(bracket, lowest.get(entry, bracket))

    rows = ',\n'.join('(%d, %d)' % (entry, bracket) for entry, bracket in sorted(lowest.items()))
    sql = """-- T-048: twink gear candidates for the twink_gear checkpoint step. Generated by tools/gmtools/twink_candidates.py
-- from T-045's shortlist (top two per bracket, item class, subclass, slot and primary stat); each item at the
-- lowest bracket it qualifies for. The tuned items in twink_item are added at load. Idempotent.

CREATE TABLE IF NOT EXISTS `gmtools_twink_candidate` (
    `entry`   INT UNSIGNED NOT NULL,
    `bracket` TINYINT UNSIGNED NOT NULL COMMENT 'lowest level the item is a twink candidate for',
    PRIMARY KEY (`entry`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='GM tools: twink gear candidates (T-048)';

DELETE FROM `gmtools_twink_candidate`;
INSERT INTO `gmtools_twink_candidate` (`entry`, `bracket`) VALUES
%s;
""" % rows
    with open(args.output, 'wb') as f:
        f.write(sql.replace('\n', '\r\n').encode('utf-8'))
    print('%d candidates written to %s' % (len(lowest), args.output))


if __name__ == '__main__':
    main()
