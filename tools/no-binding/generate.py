"""Generate portable no-binding updates from an explicit item-template TSV export."""
import argparse
import csv
from datetime import datetime
from pathlib import Path

UINT32_MAX = 2**32 - 1
ITEM_SPARSE_HASH = 2442913102
ACCOUNT_BOUND = 0x08000000


def uint32(value):
    result = int(value)
    if not 0 <= result <= UINT32_MAX:
        raise ValueError('value outside uint32: ' + str(value))
    return result


def ids(value):
    result = {uint32(token) for token in value.replace(',', ' ').split()}
    if 0 in result:
        raise ValueError('protected IDs must be nonzero')
    return result


def read_catalog(path):
    fields = ('entry', 'class', 'bonding', 'quality', 'startquest', 'flags')
    rows = {}
    with Path(path).open(encoding='utf-8-sig', newline='') as stream:
        for raw in csv.DictReader(stream, delimiter='\t'):
            raw = {key.lower(): value for key, value in raw.items()}
            row = {key: uint32(raw[key]) for key in fields}
            entry = row['entry']
            if not entry or entry in rows:
                raise ValueError('missing or duplicate item entry: ' + str(entry))
            rows[entry] = row
    if not rows:
        raise ValueError('empty catalog')
    return rows


def eligible(row, protected):
    return (row['entry'] not in protected and row['class'] != 12 and
            row['bonding'] < 4 and row['quality'] != 6 and not row['startquest'])


def numbers(values):
    return ','.join(str(value) for value in sorted(values))


def character_sql(catalog, protected, protected_guids):
    allowed = sorted(entry for entry, row in catalog.items() if eligible(row, protected))
    output = ['-- Generated by tools/no-binding/generate.py; do not edit by hand.',
              '-- Apply only when NoBinding.Enable is enabled; back up existing saves first.',
              '-- Known templates: %d; eligible: %d.' % (len(catalog), len(allowed)),
              '-- Protected entries: ' + (numbers(protected) or '(none)'),
              '-- Protected item_instance GUIDs: ' + (numbers(protected_guids) or '(none)'),
              '-- Only the soulbound bit changes. Missing/quest/progression templates stay untouched.']
    for offset in range(0, len(allowed), 1000):
        batch = allowed[offset:offset + 1000]
        output.extend(['UPDATE `item_instance`',
                       'SET `flags` = `flags` & 4294967294',
                       'WHERE (`flags` & 1) <> 0 AND `itemEntry` IN ('])
        lines = [numbers(batch[i:i + 20]) for i in range(0, len(batch), 20)]
        output.append('    ' + ',\n    '.join(lines) + ')')
        if protected_guids:
            output.append('  AND `guid` NOT IN (' + numbers(protected_guids) + ')')
        output[-1] += ';'
    return '\n'.join(output) + '\n'


def world_sql(version):
    version = datetime.strptime(version, '%Y-%m-%d %H:%M:%S').strftime('%Y-%m-%d %H:%M:%S')
    return f'''-- NoBinding item-sparse invalidation. Original item_template binding stays intact.
-- Existing hotfix history (including stack updates) is preserved; rerunning adds no duplicates.
INSERT INTO `hotfix_data` (`entry`,`type`,`hotfixDate`)
SELECT i.`entry`,{ITEM_SPARSE_HASH},'{version}'
FROM `item_template` i
LEFT JOIN `hotfix_data` h ON h.`entry`=i.`entry` AND h.`type`={ITEM_SPARSE_HASH}
  AND h.`hotfixDate`='{version}'
WHERE (i.`bonding`<>0 OR (i.`flags` & {ACCOUNT_BOUND})<>0) AND h.`entry` IS NULL;
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--catalog', type=Path, required=True)
    parser.add_argument('--protected-entries', default='')
    parser.add_argument('--protected-guids', default='', help='low item_instance GUIDs from progression/storage providers')
    parser.add_argument('--hotfix-date', required=True, help='fixed SQL datetime for this update, for reproducible reruns')
    parser.add_argument('--world-output', type=Path, required=True)
    parser.add_argument('--characters-output', type=Path, required=True)
    args = parser.parse_args()
    catalog = read_catalog(args.catalog)
    protected, guids = ids(args.protected_entries), ids(args.protected_guids)
    world = world_sql(args.hotfix_date)
    characters = character_sql(catalog, protected, guids)
    for path, sql in [(args.world_output, world), (args.characters_output, characters)]:
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open('w', encoding='utf-8', newline='\n') as stream:
            stream.write(sql)
    print('Templates=%d; eligible=%d; protected entries=%d; protected instances=%d' %
          (len(catalog), sum(eligible(row, protected) for row in catalog.values()), len(protected), len(guids)))


if __name__ == '__main__':
    main()
